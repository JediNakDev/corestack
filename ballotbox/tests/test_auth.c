/*
 * A FIFO is the case S_ISREG exists for, and it is the one that cannot be
 * caught by asserting on a return value alone: a bare open(O_RDONLY) on a
 * FIFO BLOCKS UNTIL A WRITER APPEARS, so the check never runs and the session
 * hangs holding a client that has already handshaked. This case was written
 * against exactly that bug and reproduced it.
 *
 * The watchdog is the assertion. It distinguishes "refused" from "never
 * returned" with no elapsed time to measure and no threshold to tune, which
 * is this suite's rule for every case that could hang.
 */
static int test_fifo_is_refused_not_read(void)
{
    reset_root();
    make_dir();
    CHECK(mkfifo(TEST_SECRET_PATH, 0600) == 0, "fixture: mkfifo");

    unsigned char out[64];
    alarm(WATCHDOG_SECS);
    int rc = auth_secret_load(TEST_ROOT, out, sizeof out);
    alarm(0);
    CHECK(rc == -1, "a FIFO must be refused on S_ISREG, not opened and read");

    reset_root();
    return 0;
}

static int test_valid_secret_loads(void)
{
    reset_root();
    make_dir();
    CHECK(write_secret(32, 0600) == 0, "fixture: write a 32-byte secret");

    unsigned char out[64];
    int rc = auth_secret_load(TEST_ROOT, out, sizeof out);
    CHECK(rc == 32, "a 32-byte, 0600 secret must load and return its length");

    reset_root();
    return 0;
}

/* The chmod recovery: 0644 refuses, chmod 0600 in place, the very next
 * attempt in the same process succeeds - no restart, nothing cached. */
static int test_chmod_recovers_without_restart(void)
{
    reset_root();
    make_dir();
    CHECK(write_secret(32, 0644) == 0, "fixture: write a 0644 secret");

    unsigned char out[64];
    int rc = auth_secret_load(TEST_ROOT, out, sizeof out);
    CHECK(rc == -1, "first attempt against a loose file must be refused");

    CHECK(chmod(TEST_SECRET_PATH, 0600) == 0, "chmod 0600 must succeed");

    rc = auth_secret_load(TEST_ROOT, out, sizeof out);
    CHECK(rc == 32,
          "the same process, same file, must recover with no restart");

    reset_root();
    return 0;
}

/* The loader never repairs - it validates or refuses, and it never calls
 * chmod on a file it did not create. Creation belongs to `make secret`, so a
 * loose secret staying loose is the whole point rather than a missing repair.
 */
static int test_load_never_repairs(void)
{
    reset_root();
    make_dir();
    CHECK(write_secret(32, 0644) == 0, "fixture: write a 0644 secret");

    unsigned char out[64];
    CHECK(auth_secret_load(TEST_ROOT, out, sizeof out) == -1,
          "loading a loose existing secret must refuse, not repair");

    struct stat st;
    CHECK(stat(TEST_SECRET_PATH, &st) == 0, "the file must still be there");
    CHECK((st.st_mode & 0777) == 0644,
          "the loader must not have touched the mode");

    reset_root();
    return 0;
}

/* === B. Socketpair, scripted peer ======================================== */

/*
 * The session pair is hand-built rather than handshaked.
 *
 * session_t is three fields and libtetrissh's traffic functions ask only that
 * `established` is set and that both ends hold the same key, so two structs
 * over a socketpair speak exactly the frames a real session speaks. Running a
 * real session_accept() here would add an RSA handshake, a certificate on
 * disk and a second fork to every case in this section, and would test
 * libtetrissh, which tests/test_session.c already does.
 */
static void fake_session(session_t *s, int fd)
{
    memset(s, 0, sizeof *s);
    memset(s->key, 0x5a, sizeof s->key);
    s->fd = fd;
    s->established = 1;
}

static int write_file(const char *path, const void *data, size_t len,
                      mode_t mode)
{
    int fd = open(path, O_CREAT | O_WRONLY | O_TRUNC, mode);
    if (fd < 0)
        return -1;
    if (len > 0 && write(fd, data, len) != (ssize_t)len)
    {
        close(fd);
        return -1;
    }
    close(fd);
    return chmod(path, mode);
}

static void wire_reset(void)
{
    (void)unlink(WIRE_RC);
    (void)unlink(WIRE_SECRET);
    (void)unlink(WIRE_DB "/catalog.txt");
    (void)unlink(WIRE_DB "/user.dat");
    (void)unlink(WIRE_SOCK);
    (void)unlink(WIRE_SILENT);
    (void)rmdir(WIRE_ROOT "/auth");
    (void)rmdir(WIRE_ROOT "/run");
    (void)rmdir(WIRE_DB);
    (void)rmdir(WIRE_ROOT);
}

/* Build an isolated working directory with a 32-byte 0600 secret and the
 * relative paths each child uses. The child chdirs here before
 * auth_retry_handler(), so no case can touch the repo's own .tetrishrc or
 * auth/jwt_secret. */
static int wire_setup(void)
{
    unsigned char secret[32];

    wire_reset();
    (void)mkdir(WIRE_ROOT, 0700);
    (void)mkdir(WIRE_ROOT "/auth", 0700);
    (void)mkdir(WIRE_ROOT "/run", 0700);
    (void)mkdir(WIRE_DB, 0700);

    memset(secret, 0x2b, sizeof secret);
    return write_file(WIRE_SECRET, secret, sizeof secret, 0600);
}

/* rc == NULL removes the file, which is #60 decision 3's case. */
static int wire_rc(const char *rc)
{
    if (rc == NULL)
    {
        (void)unlink(WIRE_RC);
        return 0;
    }
    return write_file(WIRE_RC, rc, strlen(rc), 0600);
}

/* --- the scripted peer's two verbs --- */

static int put(session_t *cli, const char *method, const char *path,
               const char *body)
{
    htttp_request_t req;
    uint8_t out[2048];
    uint32_t out_len = sizeof out;

    memset(&req, 0, sizeof req);
    snprintf(req.method, sizeof req.method, "%s", method);
    snprintf(req.path, sizeof req.path, "%s", path);
    if (body != NULL)
    {
        req.body = (const uint8_t *)body;
        req.body_len = (uint32_t)strlen(body);
    }
    if (htttp_serialize_request(&req, out, &out_len) != HTTTP_OK)
        return -1;
    return session_send(cli, out, out_len) == SESSION_OK ? 0 : -1;
}

/* The status of the next response, or -1 if the peer hung up or sent
 * something that is not one. body, when given, receives the NUL-terminated
 * body - which is where the token rides. */
static int get(session_t *cli, char *body, size_t cap)
{
    uint8_t buf[SESSION_MAX_FRAME];
    uint32_t len = sizeof buf;
    htttp_response_t res;

    if (body != NULL && cap > 0)
        body[0] = '\0';
    if (session_recv(cli, buf, &len) != SESSION_OK)
        return -1;
    if (htttp_parse_response(buf, len, &res) != HTTTP_OK)
        return -1;
    if (body != NULL && cap > 0 && res.body != NULL && res.body_len < cap)
    {
        memcpy(body, res.body, res.body_len);
        body[res.body_len] = '\0';
    }
    return res.status;
}

/* --- the driver --- */

typedef struct
{
    const char *rc;              /* .tetrishrc contents, or NULL for none    */
    int (*child)(session_t *sh); /* runs in the forked session process       */
    int (*peer)(session_t *cli); /* runs here, scripting the client          */
} wire_case_t;

/*
 * Run one case: the child is the session, this process is the client.
 *
 * The child's EXIT CODE IS ITS ASSERTION - every child below returns a
 * distinct small integer per thing it checked, because a child cannot use
 * CHECK() and printing from it would interleave with this process's output.
 */
static int drive(const wire_case_t *w)
{
    int sv[2];

    CHECK(wire_rc(w->rc) == 0, "fixture: write .tetrishrc");
    CHECK(socketpair(AF_UNIX, SOCK_STREAM, 0, sv) == 0, "socketpair");

    pid_t pid = fork();
    CHECK(pid >= 0, "fork");
    if (pid == 0)
    {
        session_t sh;

        close(sv[0]);
        if (chdir(WIRE_ROOT) != 0)
            _exit(250);
        alarm(WATCHDOG_SECS);
        fake_session(&sh, sv[1]);
        _exit(w->child(&sh));
    }
    close(sv[1]);

    session_t cli;
    fake_session(&cli, sv[0]);
    int rc = w->peer(&cli);
    close(sv[0]);

    int status = 0;
    while (waitpid(pid, &status, 0) < 0 && errno == EINTR)
        ;

    if (rc != 0)
        return -1;
    CHECK(WIFEXITED(status), "the session child died rather than returning");
    if (WEXITSTATUS(status) != 0)
        test_output_failure_detailf(__FILE__, __LINE__,
                                    "the session child failed assertion %d",
                                    WEXITSTATUS(status));
    CHECK(WEXITSTATUS(status) == 0, "the session child reported a failure");
    return 0;
}

/* The child every case with nothing to check after the exchange uses. */
static int child_expect_ok(session_t *sh)
{
    return auth_retry_handler(sh) == AUTH_OK ? 0 : 1;
}

static int child_expect_drop(session_t *sh)
{
    return auth_retry_handler(sh) == AUTH_DROP ? 0 : 1;
}

