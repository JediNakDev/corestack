/*
 * LOAD-BEARING. Four processes registering the same username at once, swept
 * over a growing table.
 *
 * Four children against an EMPTY table all land on page 0, which has free
 * slots, and there the transaction alone is sufficient - so a single-shot
 * version of this case passes on a build with the semaphore deleted. The
 * semaphore's entire reason for existing is the append onto a FULL last page,
 * which is why this sweeps rather than races once. It deliberately does not
 * encode the page size or the row width: it fills, races, fills more, races
 * again, so it keeps crossing page boundaries the day a column is added.
 */
#define SWEEP_ROUNDS 16
#define RACERS 4

static int fill_rows(int first_id, int n)
{
    char sql[512];
    char body[2048];

    for (int i = 0; i < n; i++)
    {
        snprintf(sql, sizeof sql,
                 "insert into " TETRISAUTH_DB_TABLE " values (%d, 'filler%d', "
                 "'00112233445566778899aabbccddeeff', "
                 "'00112233445566778899aabbccddeeff"
                 "00112233445566778899aabbccddeeff', 1000, 0);",
                 first_id + i, first_id + i);
        if (query(sql, body, sizeof body) != 0)
            return -1;
    }
    return 0;
}

/* One round: RACERS processes send REGISTER for the same name at the same
 * time. Exactly one may be told 200. */
static int race_once(const char *name)
{
    int sv[RACERS][2];
    pid_t pid[RACERS];
    session_t cli[RACERS];
    char body[64];
    int accepted = 0, refused = 0;

    snprintf(body, sizeof body, "%s\nrace-password", name);

    for (int i = 0; i < RACERS; i++)
    {
        CHECK(socketpair(AF_UNIX, SOCK_STREAM, 0, sv[i]) == 0, "socketpair");
        pid[i] = fork();
        CHECK(pid[i] >= 0, "fork");
        if (pid[i] == 0)
        {
            session_t sh;

            for (int j = 0; j < i; j++)
                close(sv[j][0]);
            close(sv[i][0]);
            if (chdir(WIRE_ROOT) != 0)
                _exit(250);
            alarm(WATCHDOG_SECS);
            fake_session(&sh, sv[i][1]);
            _exit(auth_retry_handler(&sh) == AUTH_OK ? 0 : 1);
        }
        close(sv[i][1]);
        fake_session(&cli[i], sv[i][0]);
    }

    /* Every REGISTER goes out before any status is read, so the four of them
     * are genuinely contending rather than queueing behind this process's
     * reads. */
    for (int i = 0; i < RACERS; i++)
        CHECK(put(&cli[i], "REGISTER", "/auth/register", body) == 0,
              "send REGISTER");

    for (int i = 0; i < RACERS; i++)
    {
        int status = get(&cli[i], NULL, 0);
        if (status == 200)
            accepted++;
        else if (status == 409)
            refused++;
        else
            CHECK(0, "a racing REGISTER answered neither 200 nor 409");
    }

    for (int i = 0; i < RACERS; i++)
    {
        close(sv[i][0]);
        while (waitpid(pid[i], NULL, 0) < 0 && errno == EINTR)
            ;
    }

    CHECK(accepted == 1, "exactly one racing REGISTER may be accepted");
    CHECK(refused == RACERS - 1, "every other racer must be told 409");
    return 0;
}

static int test_registration_sweep(void)
{
    char name[MAX_USER_NAME];
    int next_filler = 100000;

    CHECK(wire_rc(RC_LIVE_DB) == 0, "fixture: write .tetrishrc");

    for (int round = 0; round < SWEEP_ROUNDS; round++)
    {
        CHECK(fill_rows(next_filler, round) == 0,
              "fixture: pre-fill the table");
        next_filler += round;

        snprintf(name, sizeof name, "racer%d", round);
        CHECK(race_once(name) == 0, "the four-process race");
        CHECK(rows_named(name) == 1,
              "the table must hold exactly one row for a raced username");
    }
    return 0;
}

