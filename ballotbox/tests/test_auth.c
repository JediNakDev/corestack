/* A frame that is not a request is 400 and the exchange carries on: it is a
 * broken client, not a wrong password, so it costs no attempt. */
static int peer_garbage_then_guest(session_t *cli)
{
    const char junk[] = "this is not a request line";

    CHECK(session_send(cli, (const uint8_t *)junk, sizeof junk - 1) ==
              SESSION_OK,
          "send junk");
    CHECK(get(cli, NULL, 0) == 400, "an unparseable frame must be 400");
    CHECK(put(cli, "GUEST", "/auth/guest", NULL) == 0, "send GUEST");
    CHECK(get(cli, NULL, 0) == 200, "the exchange must survive a 400");
    return 0;
}

static int test_unparseable_frame_is_400(void)
{
    wire_case_t w = {RC_NO_DB, child_expect_ok, peer_garbage_then_guest};
    return drive(&w);
}

/*
 * The pre-auth gate answers 401, and that 401 DOES NOT COUNT.
 *
 * auth_max_attempts is 2 here, and four JOINs go out before the GUEST. If the
 * counter moved on a refusal that answers a JOIN, the connection would be gone
 * before the GUEST arrived - and the server's count would also be out of step
 * with the client's, which mirrors AUTH_STATUS_COUNTS() and scopes it by the
 * method it is waiting on.
 */
static const char RC_TWO_ATTEMPTS[] = "db_ipc = run/nothing-here.sock\n"
                                      "db_timeout = 300\n"
                                      "auth_max_attempts = 2\n"
                                      "auth_pbkdf2_iters = " TEST_ITERS "\n";

static int peer_joins_then_guest(session_t *cli)
{
    for (int i = 0; i < 4; i++)
    {
        CHECK(put(cli, "JOIN", "/room/0", NULL) == 0, "send JOIN");
        CHECK(get(cli, NULL, 0) == 401, "a pre-auth JOIN must be 401");
    }
    CHECK(put(cli, "GUEST", "/auth/guest", NULL) == 0, "send GUEST");
    CHECK(get(cli, NULL, 0) == 200,
          "four pre-auth 401s must not have spent the attempt budget");
    return 0;
}

static int test_pre_auth_401_does_not_count(void)
{
    wire_case_t w = {RC_TWO_ATTEMPTS, child_expect_ok, peer_joins_then_guest};
    return drive(&w);
}

/* Everything a malformed credential can be, all of it decided before any
 * connection is opened - which is what asserting 400 rather than 500 proves,
 * since db_ipc names nothing. */
static int peer_bad_bodies(session_t *cli)
{
    CHECK(put(cli, "LOGIN", "/auth/login", "no-newline-here") == 0,
          "send LOGIN");
    CHECK(get(cli, NULL, 0) == 400, "a body with no LF must be 400");

    CHECK(put(cli, "LOGIN", "/auth/login", "\npassword") == 0, "send LOGIN");
    CHECK(get(cli, NULL, 0) == 400, "an empty username must be 400");

    CHECK(put(cli, "LOGIN", "/auth/login", "bob\n") == 0, "send LOGIN");
    CHECK(get(cli, NULL, 0) == 400, "an empty password must be 400");

    CHECK(put(cli, "LOGIN", "/auth/login", "bo b\npassword") == 0,
          "send LOGIN");
    CHECK(get(cli, NULL, 0) == 400,
          "a username outside the allowlist must be 400");

    CHECK(put(cli, "LOGIN", "/auth/login", "o'brien\npassword") == 0,
          "send LOGIN");
    CHECK(get(cli, NULL, 0) == 400, "a quote in a username must be 400");

    CHECK(put(cli, "LOGIN", "/auth/login", "sixteencharname1\npassword") == 0,
          "send LOGIN");
    CHECK(get(cli, NULL, 0) == 400, "a 16-character username must be 400");

    CHECK(put(cli, "REGISTER", "/auth/register", "bob\nshort") == 0,
          "send REGISTER");
    CHECK(get(cli, NULL, 0) == 400,
          "a password under 8 bytes must be 400 at REGISTER");

    CHECK(put(cli, "GUEST", "/auth/guest", NULL) == 0, "send GUEST");
    CHECK(get(cli, NULL, 0) == 200,
          "no 400 may have counted against the budget");
    return 0;
}

/* The cap is 15 INCLUSIVE, and a boundary asserted only from the refusing side
 * passes on an implementation that is off by one in the permissive direction.
 * A 500 here means the name was accepted and the exchange reached a database
 * that is not there, which is the only way to see "not refused" without one. */
static int peer_name_boundary(session_t *cli)
{
    CHECK(put(cli, "LOGIN", "/auth/login", "fifteenchars_ok\npassword") == 0,
          "send LOGIN");
    CHECK(get(cli, NULL, 0) == 500,
          "a legal 15-character name must reach the database, not be refused");

    CHECK(put(cli, "GUEST", "/auth/guest", NULL) == 0, "send GUEST");
    CHECK(get(cli, NULL, 0) == 200, "a 500 must not have spent an attempt");
    return 0;
}

