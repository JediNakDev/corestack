/* Kills the process if a case that must not block does. Asserts "it returned",
 * not "it returned within N ms", so there is no threshold to tune. */
#define WATCHDOG_SECS 20

/* Low enough that the four-process sweep costs a fraction of a second and high
 * enough to still be a real PBKDF2 call. #60 decision 8 granted the key for
 * exactly this, and refused a floor: any floor low enough for a test stops
 * nobody in production. */
#define TEST_ITERS "1000"

static int tests_run = 0, tests_failed = 0, tests_skipped = 0;

#define CHECK(cond, msg)                                                       \
    do                                                                         \
    {                                                                          \
        if (!(cond))                                                           \
        {                                                                      \
            test_output_failure_detail(msg, __FILE__, __LINE__);               \
            return -1;                                                         \
        }                                                                      \
    } while (0)

static void run(const char *name, int (*fn)(void))
{
    tests_run++;
    if (fn() != 0)
    {
        tests_failed++;
        test_output_fail(name);
    }
    else
        test_output_pass(name);
}

static void reset_root(void)
{
    (void)unlink(TEST_SECRET_PATH);
    (void)rmdir(TEST_ROOT "/auth");
    (void)rmdir(TEST_ROOT);
}

static void make_dir(void)
{
    (void)mkdir(TEST_ROOT, 0700);
    (void)mkdir(TEST_ROOT "/auth", 0700);
}

/*
 * Write len arbitrary bytes to TEST_SECRET_PATH at the given mode. Returns 0
 * or -1, and the caller must CHECK it: a silently failed fixture leaves the
 * file ABSENT, and four of the cases below expect -1 from an absent file too,
 * so an unchecked failure here passes them for entirely the wrong reason.
 */
static int write_secret(size_t len, mode_t mode)
{
    unsigned char buf[64];
    int fd = open(TEST_SECRET_PATH, O_CREAT | O_WRONLY | O_TRUNC, mode);
    if (fd < 0)
        return -1;

    memset(buf, 'k', sizeof buf);
    size_t written = 0;
    while (written < len)
    {
        size_t chunk = len - written;
        if (chunk > sizeof buf)
            chunk = sizeof buf;
        ssize_t n = write(fd, buf, chunk);
        if (n <= 0)
        {
            close(fd);
            return -1;
        }
        written += (size_t)n;
    }
    close(fd);

    /* O_CREAT's mode is masked by umask, so set it explicitly. */
    return chmod(TEST_SECRET_PATH, mode);
}

