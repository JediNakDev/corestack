/*
 * LOAD-BEARING. GUEST with the database provably absent.
 *
 * db_ipc names a socket that does not exist, so anything on this path that
 * reached for the database would fail loudly rather than silently pass. This
 * and the prompt-500 case below are the only tests in the suite that REQUIRE
 * the runner's absence, which is what makes them the only ones that cannot be
 * skipped into uselessness on a box with no JVM.
 */
static const char RC_NO_DB[] = "db_ipc = run/nothing-here.sock\n"
                               "db_timeout = 300\n"
                               "auth_pbkdf2_iters = " TEST_ITERS "\n";

static int child_guest_is_nameless(session_t *sh)
{
    char name[MAX_USER_NAME];

    if (auth_retry_handler(sh) != AUTH_OK)
        return 1;

    /* Before any login at all, and after an accepted GUEST, the stamp is empty
     * - which is what makes room.c fall back to "Player %d". */
    auth_get_name(name, sizeof name);
    return name[0] == '\0' ? 0 : 2;
}

static int peer_guest(session_t *cli)
{
    CHECK(put(cli, "GUEST", "/auth/guest", NULL) == 0, "send GUEST");
    CHECK(get(cli, NULL, 0) == 200,
          "GUEST must be 200 with no database at all");
    return 0;
}

static int test_guest_needs_no_database(void)
{
    wire_case_t w = {RC_NO_DB, child_guest_is_nameless, peer_guest};
    return drive(&w);
}

