/* Tests for libtetrisauth's entry point.
 *
 * Phase 4 (#54). One file, three sections, split at #55's line rather than at
 * "unit vs integration", following tests/test_db.c's macro and
 * driver shape:
 *
 *   A. No socket, no server   #58's jwt_secret fixtures, which are pure
 *                             return-value checks against auth_secret_load().
 *   B. Socketpair, scripted peer   auth_retry_handler() and auth_offer(): the
 *                             control flow, the status mapping, both
 *                             degradations, and the scrub.
 *   C. Live SocketRunner   the queries themselves, skipped without a JVM.
 *
 * Three things about this suite that are decisions, not omissions:
 *
 *   - EVERY CASE IN B AND C FORKS. #55's file-statics never reset and the
 *     config load freezes on first success, so a case that wants a different
 *     auth_max_attempts or a fresh counter gets one by being a child process.
 *     That is the design being tested honestly: one process, one client. There
 *     is deliberately no auth_reset_for_test().
 *   - NO CASE ASSERTS ON ELAPSED WALL-CLOCK TIME, including the two that exist
 *     to pin deadlines. Both assert a 500 under an alarm() watchdog, which
 *     distinguishes "returned with the right answer" from "hung" with no
 *     tolerance to tune.
 *   - TETRISH_REQUIRE_RUNNER=1 turns a skip into a failure, and CI sets it.
 *     The skip line names `java` and the jar separately, because they are
 *     different problems with different fixes and one message for both is why
 *     nobody noticed the database tests had never run on a push.
 *
 * The two load-bearing cases, so they are not read as ordinary coverage: the
 * four-process registration sweep over growing pre-fill counts (four children
 * against an empty table all land on page 0, which has free slots, so the
 * transaction alone is sufficient there and the case passes on a build with
 * the semaphore deleted), and GUEST succeeding with the database provably
 * absent.
 *
 * WHERE #54's SECTION LINE MOVED, AND WHY. #55's resolution expected
 * auth_offer() to be reachable "with no socket and no server", because it
 * takes a parsed request and a SessionState. That is still false, for a
 * smaller reason than it used to be: it answers 409 on the wire itself, so it
 * needs the session auth_retry_handler() retained. Every auth_offer() case is
 * therefore in section B, and the pure rules underneath it - the body split,
 * the username allowlist, the password bounds - are asserted through the wire
 * rather than by reaching into core/src/libtetrisauth/auth.h, which is
 * private for the same reason token.c's parsing statics are.
 *
 * ONE CASE ASSERTS A DELETED MECHANISM BY ITS ABSENCE. #48 decision 3 was
 * overturned after this suite was first written: guest is terminal, so no
 * credential can be offered after the exchange resolves, so nothing post-login
 * can spend an attempt and the shutdown()-as-drop-channel is gone. The refusal
 * case offers five auth methods against auth_max_attempts of 2 and requires
 * the connection to survive all five. Delete that case and the mechanism can
 * come back unnoticed.
 *
 * Full checklist: #54, plus #58's five secret-file cases.
 *
 * === #58's secret-file cases (Section A) ===
 *
 * All fixtures under one temp TETRISH_ROOT, no JVM, no fork - varying a file
 * on disk rather than an rc value holds no static and needs none of the
 * process-isolation the rest of this suite pays for. #56 means a 500 never
 * moves the attempt counter, so these are pure return-value checks against
 * auth_secret_load() directly.
 *
 * NOTHING HERE CREATES A SECRET, and no case asserts that anything does. The
 * key is generated by the `secret` target in the Makefile, not by
 * libtetrisauth, so that a login handler cannot mint a signing key and
 * silently rotate every outstanding token. The absent case below therefore
 * expects a refusal, and it is the assertion that pins that split.
 *
 * Run from the repo root: make test */
