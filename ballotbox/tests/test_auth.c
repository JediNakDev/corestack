/* Build a parsed request the way session.c's POLLIN arm does: serialize into a
 * buffer and parse it back, so req->body points into buf exactly as his does
 * and the scrub has something real to clear. */
static int build_request(uint8_t *buf, size_t cap, htttp_request_t *req,
                         const char *method, const char *path, const char *body)
{
    htttp_request_t out;
    uint32_t len = (uint32_t)cap;

    memset(&out, 0, sizeof out);
    snprintf(out.method, sizeof out.method, "%s", method);
    snprintf(out.path, sizeof out.path, "%s", path);
    if (body != NULL)
    {
        out.body = (const uint8_t *)body;
        out.body_len = (uint32_t)strlen(body);
    }
    if (htttp_serialize_request(&out, buf, &len) != HTTTP_OK)
        return -1;
    return htttp_parse_request(buf, len, req) == HTTTP_OK ? 0 : -1;
}

/* Substring search over a buffer that may hold NULs. Written here rather than
 * calling memmem(), which is not in every libc this might be built against. */
static int contains(const uint8_t *hay, size_t hay_len, const char *needle)
{
    size_t n = strlen(needle);

    if (n == 0 || hay_len < n)
        return 0;
    for (size_t i = 0; i + n <= hay_len; i++)
        if (memcmp(hay + i, needle, n) == 0)
            return 1;
    return 0;
}

/*
 * Identity is fixed by the pre-auth exchange, so every credential offered
 * afterwards is refused - in every state, by every method, with no exchange
 * run and no attempt spent.
 *
 * The states are swept rather than sampled because "409 in every state" is the
 * whole rule: an implementation that consulted SessionState and got one arm
 * wrong would pass a single-state case.
 */
static int child_offer(session_t *sh)
{
    uint8_t buf[2048];
    htttp_request_t req;
    SessionState idle, in_room, playing;

    if (auth_retry_handler(sh) != AUTH_OK)
        return 1;

    memset(&idle, 0, sizeof idle);
    idle.phase = SESSION_IDLE;
    idle.room_id = ROOM_NONE;
    in_room = idle;
    in_room.phase = SESSION_WAITING;
    in_room.room_id = 3;
    playing = in_room;
    playing.phase = SESSION_PLAYING;

    /* Not one of the three methods: consumed nothing, answered nothing, and the
     * dispatch switch below it carries on untouched. */
    if (build_request(buf, sizeof buf, &req, "JOIN", "/room/0", NULL) != 0)
        return 2;
    if (auth_offer(&req, &idle))
        return 3;

    if (build_request(buf, sizeof buf, &req, "GUEST", "/auth/guest", NULL) != 0)
        return 4;
    if (!auth_offer(&req, &idle))
        return 5;

    if (build_request(buf, sizeof buf, &req, "REGISTER", "/auth/register",
                      "bob\npassphrase") != 0)
        return 6;
    if (!auth_offer(&req, &in_room))
        return 7;

    /* Idle is the state the superseded design ran the exchange in, so it is the
     * one most likely to grow an exception back. With db_ipc naming nothing, a
     * 409 rather than a 500 is also proof that no connection was attempted. */
    if (build_request(buf, sizeof buf, &req, "LOGIN", "/auth/login",
                      "bob\nhunter2hunter2") != 0)
        return 8;
    if (!auth_offer(&req, &idle))
        return 9;

    /* THE PLAINTEXT IS GONE BY THE TIME CONTROL COMES BACK. Refusing the
     * request does not unread it, and this is the one scrub in the design
     * reachable from a test, because it happens in the caller's buffer rather
     * than in a frame that has already returned. */
    if (contains(buf, sizeof buf, "hunter2hunter2"))
        return 10;

    /* Nothing above may have spent an attempt: auth_max_attempts is 2 here,
     * four offers went out, and the session must still be alive. */
    if (build_request(buf, sizeof buf, &req, "LOGIN", "/auth/login",
                      "bob\npassword") != 0)
        return 11;
    if (!auth_offer(&req, &idle))
        return 12;

    return 0;
}

